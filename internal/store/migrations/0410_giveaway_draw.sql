-- Giveaways run until their end date and draw then, like Telegram's. The
-- buyer's Stars wait on the escrow account in between. Giveaways drawn at
-- payment before this (their ledger rows and channel_gift_boosts) stay as
-- they are.

-- what the buyer picked on the form; NULL for every other kind of form
ALTER TABLE payment_forms ADD COLUMN giveaway jsonb;

-- channel_id has no foreign key: a deleted channel's giveaway still has to
-- be refunded. Channels are only ever marked deleted, but this doesn't lean
-- on that.
CREATE TABLE giveaways (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id bigint NOT NULL UNIQUE,
    kind text NOT NULL CHECK (kind IN ('premium', 'stars')),
    buyer_id bigint NOT NULL REFERENCES users(id),
    channel_id bigint NOT NULL,
    additional bigint[] NOT NULL DEFAULT '{}',
    countries text[] NOT NULL DEFAULT '{}',
    only_new boolean NOT NULL DEFAULT false,
    winners_visible boolean NOT NULL DEFAULT false,
    prize_description text NOT NULL DEFAULT '',
    quantity int NOT NULL CHECK (quantity > 0),
    months int NOT NULL DEFAULT 0,
    days int NOT NULL DEFAULT 0,
    stars bigint NOT NULL CHECK (stars > 0), -- held on escrow until the draw
    started_at int NOT NULL,
    until_date int NOT NULL,
    launch_id int NOT NULL DEFAULT 0,  -- messageActionGiveawayLaunch
    post_id int NOT NULL DEFAULT 0,    -- messageMediaGiveaway
    state text NOT NULL DEFAULT 'running' CHECK (state IN ('running', 'drawn', 'refunded')),
    drawn_at int NOT NULL DEFAULT 0,
    refunded_stars bigint NOT NULL DEFAULT 0,
    results_id int NOT NULL DEFAULT 0,       -- messageActionGiveawayResults
    results_post_id int NOT NULL DEFAULT 0   -- messageMediaGiveawayResults
);
CREATE INDEX giveaways_due ON giveaways(until_date) WHERE state = 'running';
CREATE INDEX giveaways_channel ON giveaways(channel_id);

CREATE TABLE giveaway_winners (
    giveaway_id bigint NOT NULL REFERENCES giveaways(id),
    user_id bigint NOT NULL REFERENCES users(id),
    stars bigint NOT NULL DEFAULT 0,          -- the Stars prize
    transaction_id text NOT NULL DEFAULT '',  -- its ledger row
    notified boolean NOT NULL DEFAULT false,  -- the prize message went out
    PRIMARY KEY (giveaway_id, user_id)
);
CREATE INDEX giveaway_winners_unnotified ON giveaway_winners(giveaway_id) WHERE NOT notified;

-- Premium a channel gave, drawn or to chosen people, comes as a gift code
-- the app opens with checkGiftCode. It is applied when given, so it shows as
-- used.
CREATE TABLE gift_codes (
    slug text PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    channel_id bigint NOT NULL,
    giveaway_id bigint REFERENCES giveaways(id),
    days int NOT NULL,
    created_at int NOT NULL
);
CREATE UNIQUE INDEX gift_codes_giveaway ON gift_codes(giveaway_id, user_id) WHERE giveaway_id IS NOT NULL;

-- a running giveaway's boosts belong to nobody yet
ALTER TABLE channel_gift_boosts ALTER COLUMN user_id DROP NOT NULL;
ALTER TABLE channel_gift_boosts ADD COLUMN giveaway_id bigint REFERENCES giveaways(id);
CREATE INDEX channel_gift_boosts_giveaway ON channel_gift_boosts(giveaway_id) WHERE giveaway_id IS NOT NULL;

ALTER TABLE payment_forms DROP CONSTRAINT payment_forms_kind_check;
ALTER TABLE payment_forms ADD CONSTRAINT payment_forms_kind_check CHECK (kind IN ('premium', 'star_gift', 'stars_gift', 'giveaway'));
ALTER TABLE payment_forms ADD COLUMN channel_id bigint REFERENCES channels(id) ON DELETE CASCADE;
ALTER TABLE payment_forms ADD COLUMN quantity int NOT NULL DEFAULT 0;
ALTER TABLE payment_forms ADD COLUMN winners bigint[];

CREATE TABLE channel_gift_boosts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id bigint NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    assigned_at int NOT NULL,
    expires_at int NOT NULL,
    drawn boolean NOT NULL DEFAULT false
);
CREATE INDEX channel_gift_boosts_channel ON channel_gift_boosts(channel_id, expires_at);

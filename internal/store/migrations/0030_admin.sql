-- What the admin panel needs on top of accounts: moderation states, the
-- audit log, verification badges, countries for the phone picker and the
-- instance logo. IF NOT EXISTS everywhere because the importer creates some
-- of the same columns when it brings the web database over.

-- account_state: active, frozen (read-only), locked, banned, deleted.
-- is_suspended is locked plus "hide the account"; disabled stays the one
-- flag sign-in checks.
ALTER TABLE users ADD COLUMN IF NOT EXISTS account_state text NOT NULL DEFAULT 'active';
ALTER TABLE users ADD COLUMN IF NOT EXISTS is_suspended boolean NOT NULL DEFAULT false;
ALTER TABLE users ADD COLUMN IF NOT EXISTS premium_starts_at bigint NOT NULL DEFAULT 0;

-- actor and target are plain ids: entries outlive what they point at
CREATE TABLE IF NOT EXISTS audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id bigint NOT NULL,
    action text NOT NULL,
    target_id bigint NOT NULL DEFAULT 0,
    details jsonb NOT NULL DEFAULT '{}',
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS audit_log_action ON audit_log(action, id DESC);

CREATE TABLE IF NOT EXISTS peer_verifications (
    user_id bigint UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    channel_id bigint UNIQUE REFERENCES channels(id) ON DELETE CASCADE,
    verified_by bigint NOT NULL,
    verified_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((user_id IS NULL) <> (channel_id IS NULL))
);

-- Overrides for the built-in country list; iso2 '' is a prefix with no flag.
CREATE TABLE IF NOT EXISTS instance_countries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iso2 text NOT NULL DEFAULT '',
    country_code text NOT NULL,
    name text NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    UNIQUE (iso2, country_code)
);

CREATE TABLE IF NOT EXISTS instance_branding (
    id int PRIMARY KEY CHECK (id = 1),
    bytes bytea NOT NULL,
    mime text NOT NULL,
    width int NOT NULL DEFAULT 0,
    height int NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- Stars, Premium, star gifts and channel boosts. Table and column names
-- follow greengram-web's database.js so the importer copies rows across;
-- star_transaction_meta is folded into star_ledger.

-- Admins can schedule Premium to start later; isPremium() checks both ends.
ALTER TABLE users ADD COLUMN premium_starts_at bigint NOT NULL DEFAULT 0;

-- Built-in accounts that stand on the other side of a transaction
-- (Premium, Stars, Admin, Wallet). Made on first use.
CREATE TABLE system_accounts (
    kind text PRIMARY KEY,
    user_id bigint NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE
);

-- A balance is the sum of a user's rows; nothing caches it. reference is
-- the idempotency key, so a retried operation hits the unique index
-- instead of paying twice.
CREATE TABLE star_ledger (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    amount bigint NOT NULL CHECK (amount <> 0),
    reason text NOT NULL,
    reference text NOT NULL UNIQUE,
    created_by bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at int NOT NULL,
    transaction_id text NOT NULL UNIQUE,
    peer_id bigint REFERENCES users(id) ON DELETE SET NULL,
    title text NOT NULL DEFAULT '',
    note text NOT NULL DEFAULT '',
    months int NOT NULL DEFAULT 0,    -- Premium bought or gifted
    gift_id bigint                    -- star gift bought or converted
);
CREATE INDEX star_ledger_user ON star_ledger(user_id, id);

-- payments.getPaymentForm hands one out, sendStarsForm pays it once. Five
-- minutes, like the web's quotes.
CREATE TABLE payment_forms (
    id bigint PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind text NOT NULL CHECK (kind IN ('premium', 'star_gift', 'stars_gift')),
    recipient_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    months int NOT NULL DEFAULT 0,
    days int NOT NULL DEFAULT 0,
    gift_id bigint,
    stars bigint NOT NULL CHECK (stars > 0),
    message text NOT NULL DEFAULT '',
    hide_name boolean NOT NULL DEFAULT false,
    expires_at int NOT NULL,
    paid boolean NOT NULL DEFAULT false
);
CREATE INDEX payment_forms_expiry ON payment_forms(expires_at) WHERE NOT paid;

CREATE TABLE gift_catalog (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    emoji text NOT NULL,
    stars bigint NOT NULL CHECK (stars > 0),
    convert_stars bigint NOT NULL CHECK (convert_stars >= 0),
    premium_only boolean NOT NULL DEFAULT false,
    stock int CHECK (stock >= 0),     -- left to sell; NULL = unlimited
    stock_total int,                  -- what a limited gift started with
    enabled boolean NOT NULL DEFAULT true,
    sticker_id bigint                 -- artwork document, once media lands
);

-- One bought gift. message_id is the gift message in the owner's box;
-- displayed is "show on my profile", converted turned it into Stars.
CREATE TABLE gift_receipts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gift_id bigint NOT NULL REFERENCES gift_catalog(id),
    sender_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    owner_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    message_id int,
    cost bigint NOT NULL,
    convert_stars bigint NOT NULL,
    body text NOT NULL DEFAULT '',
    hide_name boolean NOT NULL DEFAULT false,
    displayed boolean NOT NULL DEFAULT true,
    converted boolean NOT NULL DEFAULT false,
    created_at int NOT NULL
);
CREATE INDEX gift_receipts_owner ON gift_receipts(owner_id, id);

-- Every Premium account has two slots; a moved boost waits a day.
CREATE TABLE channel_boosts (
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    slot int NOT NULL CHECK (slot IN (1, 2)),
    channel_id bigint NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
    assigned_at int NOT NULL,
    cooldown_until int NOT NULL,
    PRIMARY KEY (user_id, slot)
);
CREATE INDEX channel_boosts_channel ON channel_boosts(channel_id);

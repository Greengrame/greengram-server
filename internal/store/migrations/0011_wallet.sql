-- The crypto wallet, as greengram-web keeps it. Amounts are base units of
-- the asset (nanograms for TON), exact integers far past bigint for 18
-- decimal assets, so numeric; read them as ::text.

CREATE TABLE crypto_accounts (
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    asset text NOT NULL,
    units numeric(80, 0) NOT NULL DEFAULT 0 CHECK (units >= 0),
    PRIMARY KEY (user_id, asset)
);

-- The wallet's history, one row per balance change; units is signed.
-- event_key makes each change happen once.
CREATE TABLE crypto_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_key text NOT NULL UNIQUE,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    asset text NOT NULL,
    units numeric(80, 0) NOT NULL,
    kind text NOT NULL,
    peer_id bigint REFERENCES users(id) ON DELETE SET NULL,
    created_at int NOT NULL
);
CREATE INDEX crypto_events_user ON crypto_events(user_id, id);

-- Admin credits and debits; a request id replays to the same receipt.
CREATE TABLE crypto_admin_transactions (
    request_id text PRIMARY KEY,
    payload_hash text NOT NULL,
    transaction_id text NOT NULL UNIQUE,
    actor_id bigint NOT NULL REFERENCES users(id),
    recipient_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    asset text NOT NULL,
    units numeric(80, 0) NOT NULL,
    direction text NOT NULL CHECK (direction IN ('credit', 'debit')),
    note text NOT NULL DEFAULT '',
    created_at int NOT NULL
);

CREATE TABLE crypto_stars_quotes (
    id text PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    asset text NOT NULL,
    units numeric(80, 0) NOT NULL,
    stars bigint NOT NULL,
    stars_per_usd int NOT NULL,
    market_price text NOT NULL,
    market_source text NOT NULL,
    market_updated_at bigint NOT NULL,
    expires_at int NOT NULL,
    result jsonb
);

CREATE TABLE crypto_transfer_quotes (
    id text PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    recipient_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    asset text NOT NULL,
    units numeric(80, 0) NOT NULL,
    expires_at int NOT NULL,
    completed boolean NOT NULL DEFAULT false
);

CREATE TABLE crypto_swap_quotes (
    id text PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    from_asset text NOT NULL,
    to_asset text NOT NULL,
    from_units numeric(80, 0) NOT NULL,
    to_units numeric(80, 0) NOT NULL,
    expires_at int NOT NULL,
    quote jsonb NOT NULL,
    result jsonb
);
CREATE INDEX crypto_swap_quotes_user ON crypto_swap_quotes(user_id) WHERE result IS NULL;

-- Wallet passcode (argon2id, like sign-in passwords) and the sessions it
-- is unlocked in. version moves on every change so old unlocks die.
CREATE TABLE wallet_security (
    user_id bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    passcode_hash text NOT NULL,
    passcode_type text NOT NULL,
    failures int NOT NULL DEFAULT 0,
    locked_until int NOT NULL DEFAULT 0,
    version int NOT NULL DEFAULT 1
);

CREATE TABLE wallet_unlocks (
    session_hash text PRIMARY KEY REFERENCES sessions(token_hash) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at int NOT NULL,
    version int NOT NULL
);

-- The "DeFi" account is a second local balance, moved to and from main.
CREATE TABLE defi_accounts (
    user_id bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    created_at int NOT NULL
);

CREATE TABLE defi_balances (
    user_id bigint NOT NULL REFERENCES defi_accounts(user_id) ON DELETE CASCADE,
    asset text NOT NULL,
    units numeric(80, 0) NOT NULL DEFAULT 0 CHECK (units >= 0),
    PRIMARY KEY (user_id, asset)
);

CREATE TABLE defi_moves (
    id text PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES defi_accounts(user_id) ON DELETE CASCADE,
    asset text NOT NULL,
    units numeric(80, 0) NOT NULL,
    direction text NOT NULL CHECK (direction IN ('to_defi', 'to_main')),
    expires_at int NOT NULL,
    completed boolean NOT NULL DEFAULT false,
    created_at int NOT NULL
);

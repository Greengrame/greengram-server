-- Collectible gifts. An imported collection (ggcollectibles) is a set of
-- models, patterns and backdrops with their rarity; a catalog gift marked
-- upgradable turns into one of the collection's numbered pieces. Serial
-- numbers and the supply belong to the collection, and one catalog gift at a
-- time upgrades into it, so "issued of total" means one thing.

CREATE TABLE collectible_sets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,          -- the bundle's key, "plushpepe"
    title text NOT NULL,                -- "Plush Pepe"
    slug text NOT NULL UNIQUE,          -- links are /nft/<slug>-<num>
    original_document_id bigint,        -- the gift's own art before upgrading
    supply int NOT NULL DEFAULT 0 CHECK (supply >= 0),
    issued int NOT NULL DEFAULT 0 CHECK (issued >= 0 AND issued <= supply),
    imported_at int NOT NULL
);

-- document_id is the sticker gifts show; emoji_document_id the same art as
-- a custom emoji, what an emoji status is drawn with
CREATE TABLE collectible_models (
    set_id bigint NOT NULL REFERENCES collectible_sets(id) ON DELETE CASCADE,
    name text NOT NULL,
    document_id bigint NOT NULL,
    emoji_document_id bigint NOT NULL,
    rarity_permille int NOT NULL CHECK (rarity_permille BETWEEN 1 AND 1000),
    PRIMARY KEY (set_id, name)
);

CREATE TABLE collectible_patterns (
    set_id bigint NOT NULL REFERENCES collectible_sets(id) ON DELETE CASCADE,
    name text NOT NULL,
    document_id bigint NOT NULL,
    emoji_document_id bigint NOT NULL,
    rarity_permille int NOT NULL CHECK (rarity_permille BETWEEN 1 AND 1000),
    PRIMARY KEY (set_id, name)
);

CREATE TABLE collectible_backdrops (
    set_id bigint NOT NULL REFERENCES collectible_sets(id) ON DELETE CASCADE,
    name text NOT NULL,
    backdrop_id int NOT NULL,
    center_color int NOT NULL,
    edge_color int NOT NULL,
    pattern_color int NOT NULL,
    text_color int NOT NULL,
    rarity_permille int NOT NULL CHECK (rarity_permille BETWEEN 1 AND 1000),
    PRIMARY KEY (set_id, name)
);

-- upgrade_stars set means upgradable; transfer_stars is what moving one of
-- its collectibles costs (0: free)
ALTER TABLE gift_catalog ADD COLUMN upgrade_set_id bigint REFERENCES collectible_sets(id);
ALTER TABLE gift_catalog ADD COLUMN upgrade_stars bigint CHECK (upgrade_stars > 0);
ALTER TABLE gift_catalog ADD COLUMN transfer_stars bigint NOT NULL DEFAULT 0 CHECK (transfer_stars >= 0);
ALTER TABLE gift_catalog ADD CONSTRAINT gift_catalog_upgrade CHECK ((upgrade_set_id IS NULL) = (upgrade_stars IS NULL));
CREATE UNIQUE INDEX gift_catalog_upgrade_set ON gift_catalog(upgrade_set_id) WHERE upgrade_set_id IS NOT NULL;

-- One upgraded gift. The id is random, like Telegram's. The original_* are
-- the gift as it was sent, kept when the owner asked for them; the sender is
-- NULL when they hid their name.
CREATE TABLE unique_gifts (
    id bigint PRIMARY KEY,
    set_id bigint NOT NULL REFERENCES collectible_sets(id),
    gift_id bigint NOT NULL REFERENCES gift_catalog(id),
    num int NOT NULL CHECK (num > 0),
    slug text NOT NULL UNIQUE,
    model text NOT NULL,
    pattern text NOT NULL,
    backdrop text NOT NULL,
    original boolean NOT NULL DEFAULT false,
    original_sender_id bigint REFERENCES users(id) ON DELETE SET NULL,
    original_recipient_id bigint REFERENCES users(id) ON DELETE SET NULL,
    original_message text NOT NULL DEFAULT '',
    original_date int NOT NULL DEFAULT 0,
    created_at int NOT NULL,
    UNIQUE (set_id, num),
    FOREIGN KEY (set_id, model) REFERENCES collectible_models(set_id, name),
    FOREIGN KEY (set_id, pattern) REFERENCES collectible_patterns(set_id, name),
    FOREIGN KEY (set_id, backdrop) REFERENCES collectible_backdrops(set_id, name)
);

-- A receipt is whoever holds the gift now, upgraded or not: a person, or a
-- channel it was transferred to. upgrade_prepaid is what the sender paid on
-- top for the upgrade (already on the system account).
ALTER TABLE gift_receipts ADD COLUMN unique_id bigint UNIQUE REFERENCES unique_gifts(id);
ALTER TABLE gift_receipts ADD COLUMN upgrade_prepaid bigint NOT NULL DEFAULT 0 CHECK (upgrade_prepaid >= 0);
ALTER TABLE gift_receipts ALTER COLUMN owner_id DROP NOT NULL;
ALTER TABLE gift_receipts ADD COLUMN owner_channel_id bigint REFERENCES channels(id) ON DELETE CASCADE;
ALTER TABLE gift_receipts ADD CONSTRAINT gift_receipts_one_owner CHECK ((owner_id IS NULL) <> (owner_channel_id IS NULL));
CREATE INDEX gift_receipts_channel ON gift_receipts(owner_channel_id, id) WHERE owner_channel_id IS NOT NULL;

CREATE INDEX gift_receipts_prepaid ON gift_receipts(gift_id) WHERE upgrade_prepaid > 0 AND unique_id IS NULL AND NOT converted;

-- Upgrading and transferring are paid with forms too. receipt_id is the gift;
-- a transfer to a channel has the payer as recipient_id and the channel in
-- channel_id, like a giveaway's. upgrade_stars is a gift bought with its
-- upgrade, the part of stars that pays for it.
ALTER TABLE payment_forms DROP CONSTRAINT payment_forms_kind_check;
ALTER TABLE payment_forms ADD CONSTRAINT payment_forms_kind_check CHECK (kind IN ('premium', 'star_gift', 'stars_gift', 'giveaway', 'stars_giveaway',
    'star_gift_upgrade', 'star_gift_transfer'));
ALTER TABLE payment_forms ADD COLUMN receipt_id bigint;
ALTER TABLE payment_forms ADD COLUMN keep_details boolean NOT NULL DEFAULT false;
ALTER TABLE payment_forms ADD COLUMN upgrade_stars bigint NOT NULL DEFAULT 0;


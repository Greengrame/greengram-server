-- Accounts. Ids are kept when the web database is imported, hence BY DEFAULT.
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text NOT NULL,
    name text NOT NULL,
    password text NOT NULL,          -- argon2id PHC; '' = can't sign in
    role text NOT NULL DEFAULT 'member' CHECK (role IN ('member', 'admin')),
    disabled boolean NOT NULL DEFAULT false,
    is_system boolean NOT NULL DEFAULT false,
    is_bot boolean NOT NULL DEFAULT false,
    phone text,                      -- ggenc:v1:..., GCM context "user:<id>"
    phone_lookup text UNIQUE,        -- keyed hash, see internal/secret
    premium_until bigint NOT NULL DEFAULT 0,
    bio text NOT NULL DEFAULT '',
    username_public boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_username ON users (lower(username));

-- One row per sign-in. The cookie is only stored hashed. An app that signs
-- in over MTProto binds its auth key to the session it got over HTTPS, so
-- ending the session signs the app out too.
CREATE TABLE sessions (
    token_hash text PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_active timestamptz NOT NULL DEFAULT now(),
    user_agent text NOT NULL DEFAULT '',
    ip text NOT NULL DEFAULT '',
    -- from initConnection once an app binds
    api_id int NOT NULL DEFAULT 0,
    device_model text NOT NULL DEFAULT '',
    system_version text NOT NULL DEFAULT '',
    app_version text NOT NULL DEFAULT ''
);
CREATE INDEX sessions_user ON sessions(user_id);

ALTER TABLE auth_keys ADD COLUMN session_hash text REFERENCES sessions(token_hash) ON DELETE SET NULL;
CREATE INDEX auth_keys_session ON auth_keys(session_hash) WHERE session_hash IS NOT NULL;

-- A sign-in in progress: phone, register or QR. id is the hashed cookie.
CREATE TABLE auth_flows (
    id text PRIMARY KEY,
    state text NOT NULL,
    qr_hash text UNIQUE,
    phone text,                      -- ggenc:v1:..., context "auth-flow:<id>"
    user_id bigint REFERENCES users(id) ON DELETE CASCADE,
    expires_at timestamptz NOT NULL
);

CREATE TABLE privacy_rules (
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    key text NOT NULL,
    rules jsonb NOT NULL,
    PRIMARY KEY (user_id, key)
);
